"""Write results/numbers.tex: every number the paper quotes, taken from result files.

    python scripts/make_paper_numbers.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from jumpsim.detect import Clip, CueTracker, sphere_centre_image  # noqa: E402


def tex_escape(s: str) -> str:
    return s.replace("_", r"\_").replace("%", r"\%").replace("&", r"\&")


def main():
    res = ROOT / "results"
    out = []

    def cmd(name, val):
        out.append(f"\\newcommand{{\\{name}}}{{{val}}}")

    g = json.loads((res / "cue_geometry.json").read_text())
    ov, ov4k, bc = g["overhead 2.6 m, 720p"], g["overhead 2.6 m, 4K"], g["broadcast, 720p"]
    cmd("GEOsizeOvTen", f"{ov['centre']['10mm']['size_px']:.2f}")
    cmd("GEOsizeOvHundred", f"{ov['centre']['100mm']['size_px']:.2f}")
    cmd("GEOsizeFourKTen", f"{ov4k['centre']['10mm']['size_px']:.2f}")
    cmd("GEOsizeBcTen", f"{bc['centre']['10mm']['size_px']:.2f}")
    cmd("GEOparOvCornerTen", f"{ov['near corner']['10mm']['parallax_px']:.1f}")
    cmd("GEOparBcTen", f"{bc['centre']['10mm']['parallax_px']:.1f}")
    cmd("GEOshOvTen", f"{ov['centre']['10mm']['shadow_far_lamp_px']:.1f}")
    cmd("GEOshBcTen", f"{bc['centre']['10mm']['shadow_far_lamp_px']:.1f}")

    m = json.loads((res / "metrics.json").read_text())
    s = m["summary"]
    cmd("NumShots", s["train_shots"] + s["test_shots"])
    cmd("NumTrain", s["train_shots"])
    cmd("NumTest", s["test_shots"])
    cmd("NumTestFrames", f"{s['test_frames']:,}".replace(",", "{,}"))
    cmd("PosFrac", f"{100 * s['test_pos_frac']:.1f}")
    ev = {r["view"]: r["n_events"] for r in m["results"] if r["cues"] == "all"}
    cmd("NumEvents", ev["overhead"])

    # tracker accuracy on the scenario clips (centre error vs ground truth, px)
    errs = {"overhead": [], "broadcast": []}
    rows = []
    for d in sorted((ROOT / "data" / "clips").iterdir()):
        if not (d / "gt.json").exists():
            continue
        for v in errs:
            c = Clip.load(d, v)
            trk = CueTracker(c).track()
            pos = np.array(c.gt["pos"])[: len(trk["uv"]), 0]
            act = np.array(c.gt["active"])[: len(trk["uv"]), 0].astype(bool) & trk["found"]
            errs[v].append(np.linalg.norm(trk["uv"][act] - sphere_centre_image(c.cam, pos[act]), axis=1))
        gt = json.loads((d / "gt.json").read_text())
        apex = np.array(gt["height_max"])[:, 0].max() * 1000
        rows.append(f"\\texttt{{{tex_escape(d.name)}}} & {tex_escape(gt['note'])} & {apex:.0f}\\,mm \\\\")
    for v, e in errs.items():
        e = np.concatenate(e)
        cmd(f"TRKmedian{v.capitalize()}", f"{np.median(e):.2f}")
        cmd(f"TRKninety{v.capitalize()}", f"{np.percentile(e, 90):.2f}")
    cmd("TRKcentreErr", f"{np.median(np.concatenate(errs['broadcast'])):.2f}")
    cmd("INPUTCLIPROWS", "\n".join(rows))
    (res / "numbers.tex").write_text("% generated by scripts/make_paper_numbers.py\n" + "\n".join(out) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
